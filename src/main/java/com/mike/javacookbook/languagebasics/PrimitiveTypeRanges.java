package com.mike.javacookbook.languagebasics;

public class PrimitiveTypeRanges {

    public static void showPrimitiveTypeRange() {
        System.out.println("Byte min and max value: " + Byte.MIN_VALUE + ", " + Byte.MAX_VALUE);
        System.out.println("Short min and max value: " + Short.MIN_VALUE + ", " + Short.MAX_VALUE);
        System.out.println("Integer min and max value: " + Integer.MIN_VALUE + ", " + Integer.MAX_VALUE);
        System.out.println("Long min and max value: " + Long.MIN_VALUE + ", " + Long.MAX_VALUE);
        System.out.println("Float min and max value: " + Float.MIN_VALUE + ", " + Float.MAX_VALUE);
        System.out.println("Double min and max value: " + Double.MIN_VALUE + ", " + Double.MAX_VALUE);

    }

}
